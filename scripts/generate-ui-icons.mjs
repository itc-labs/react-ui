import { createRequire } from 'node:module';
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = fileURLToPath(new URL('../', import.meta.url));
const requireUI = createRequire(path.join(root, 'package.json'));
const React = requireUI('react');
const { renderToStaticMarkup } = requireUI('react-dom/server');
const { JSDOM } = requireUI('jsdom');
const iconRoot = path.join(root, 'src/components/icon');
const sources = JSON.parse(await readFile(path.join(iconRoot, 'sources.json'), 'utf8'));
const identities = new Set();
const inventory = new Map();
for (const source of sources) {
  const identity = `${source.variant}/${source.name}`;
  const expectedModule =
    source.family === 'heroicons'
      ? `@heroicons/react/24/${source.variant === 'bold' ? 'solid' : 'outline'}`
      : source.family === 'lucide'
        ? 'lucide-react'
        : undefined;
  if (!expectedModule || source.module !== expectedModule)
    throw new Error(`Unsupported icon source: ${identity}`);
  if (source.family === 'lucide' && !source.neutral && !source.outlineOnly)
    throw new Error(`Unpaired glyph must use outline fallback: ${identity}`);
  if (['sortAscending', 'sortDescending', 'sortUnsorted'].includes(source.name))
    throw new Error(`Reserved local state glyph: ${source.name}`);
  if (identities.has(identity)) throw new Error(`Duplicate icon: ${identity}`);
  if (!['outline', 'bold'].includes(source.variant))
    throw new Error(`Invalid variant: ${identity}`);
  if (source.outlineOnly && source.sourceVariant !== 'outline')
    throw new Error(`Outline-only glyph uses a different style: ${identity}`);
  identities.add(identity);
  const variants = inventory.get(source.name) ?? new Set();
  variants.add(source.variant);
  inventory.set(source.name, variants);
}
for (const [name, variants] of inventory) {
  if (variants.size !== 2) throw new Error(`Missing UI variant: ${name}`);
}

const pascal = (name) => name[0].toUpperCase() + name.slice(1);

const kebab = (name) => name.replace(/([a-z])([A-Z])/g, '$1-$2').toLowerCase();

const attrs = (node, isRoot = false) =>
  [...node.attributes]
    .filter(
      ({ name }) =>
        !isRoot ||
        !['width', 'height', 'xmlns', 'aria-hidden', 'focusable'].includes(name),
    )
    .map(({ name, value }) => {
      if (name === 'style')
        throw new Error('Inline styles need an explicit conversion');
      const key =
        name === 'class'
          ? 'className'
          : /^(aria|data)-/.test(name)
            ? name
            : name.replace(/[-:]([a-z])/g, (_, letter) => letter.toUpperCase());

      return `${key}=${JSON.stringify(value)}`;
    })
    .join(' ');

const jsx = (node) => {
  if (node.nodeType !== 1) throw new Error('Unexpected non-element SVG content');
  const attributes = attrs(node);

  return `<${node.tagName}${attributes ? ` ${attributes}` : ''}>${[...node.children].map(jsx).join('')}</${node.tagName}>`;
};

const groups = new Map();
for (const source of sources) {
  const { family, variant, name, module: moduleName, upstream } = source;
  const Glyph = requireUI(moduleName)[upstream];
  if (!Glyph) throw new Error(`Missing upstream glyph: ${moduleName}/${upstream}`);
  const markup = renderToStaticMarkup(React.createElement(Glyph));
  const document = new JSDOM(markup, { contentType: 'image/svg+xml' });
  const svg = document.window.document.documentElement;
  if (svg.tagName !== 'svg') throw new Error(`Invalid SVG: ${name}`);
  const dir = variant;
  const symbol = `${pascal(name)}Icon`;
  await mkdir(path.join(iconRoot, dir), { recursive: true });
  const version = requireUI(
    `${family === 'lucide' ? 'lucide-react' : '@heroicons/react'}/package.json`,
  ).version;
  const code = `/** ${moduleName}@${version}: ${upstream}. See ../licenses and THIRD_PARTY_NOTICES.md.\n * Generated by scripts/generate-ui-icons.mjs; edit sources.json and regenerate. */\nimport { IconSvg, type IconSvgProps } from '../svg';\nimport { cn } from '../../common';\n\nexport function ${symbol}({ className, ...props }: IconSvgProps) {\n  return <IconSvg ${attrs(svg, true).replace(/className="[^"]*"/g, '')} {...props} className={cn(${JSON.stringify(svg.getAttribute('class') ?? '')}, className)}>${[...svg.children].map(jsx).join('')}</IconSvg>;\n}\n`;
  if (source.neutral || source.outlineOnly) {
    const sharedDir = source.neutral ? 'custom' : 'shared';
    await mkdir(path.join(iconRoot, sharedDir), { recursive: true });
    await writeFile(path.join(iconRoot, sharedDir, `${kebab(name)}.tsx`), code);
    await writeFile(
      path.join(iconRoot, dir, `${kebab(name)}.tsx`),
      `export { ${symbol} } from '../${sharedDir}/${kebab(name)}';\n`,
    );
  } else {
    await writeFile(path.join(iconRoot, dir, `${kebab(name)}.tsx`), code);
  }
  const entries = groups.get(dir) ?? [];
  entries.push({ name, symbol, file: kebab(name) });
  groups.set(dir, entries);
  document.window.close();
}
for (const [dir, entries] of groups) {
  for (const [name, symbol] of [
    ['sortAscending', 'SortAscendingIcon'],
    ['sortDescending', 'SortDescendingIcon'],
    ['sortUnsorted', 'SortUnsortedIcon'],
  ]) {
    const file = kebab(name);
    await writeFile(
      path.join(iconRoot, dir, `${file}.tsx`),
      `export { ${symbol} } from '../custom/sort';\n`,
    );
    entries.push({ name, symbol, file });
  }

  await writeFile(
    path.join(iconRoot, dir, 'index.ts'),
    entries
      .map(({ symbol, file }) => `export { ${symbol} } from './${file}';`)
      .join('\n') + '\n',
  );
  const id = dir;
  const packName = `${dir}Icons`;
  await writeFile(
    path.join(iconRoot, dir, 'pack.ts'),
    `import { defineIconPack } from '../registry';\n${entries.map(({ symbol, file }) => `import { ${symbol} } from './${file}';`).join('\n')}\n\nexport const ${packName} = /* @__PURE__ */ defineIconPack('${id}', {\n${entries.map(({ name, symbol }) => `  ${name}: ${symbol},`).join('\n')}\n});\n`,
  );
}
const metadata = Object.fromEntries(
  sources
    .filter(({ variant }) => variant === 'outline')
    .map((source) => [
      source.name,
      {
        category: source.category,
        source: source.family,
        aliases: source.upstream,
        outlineOnly: source.outlineOnly,
        neutral: source.neutral,
      },
    ]),
);
for (const name of ['sortAscending', 'sortDescending', 'sortUnsorted']) {
  metadata[name] = {
    category: 'navigation',
    source: 'local',
    aliases: 'paired chevrons',
    outlineOnly: false,
    neutral: true,
  };
}
await writeFile(
  path.join(iconRoot, 'catalog.ts'),
  `/** Generated icon inventory; source of truth: sources.json. */\nexport const iconCatalog = ${JSON.stringify(metadata, null, 2)} as const;\nexport type CatalogIconName = keyof typeof iconCatalog;\n\n// Opt-in runtime packs; never imported by the shared controls.\nexport { outlineIcons as outlineCatalog } from './outline/pack';\nexport { boldIcons as boldCatalog } from './bold/pack';\n`,
);
await writeFile(
  path.join(iconRoot, 'names.ts'),
  `/** Generated semantic names; no glyph imports. */\nexport const iconNames = Object.freeze(${JSON.stringify(Object.keys(metadata))} as const);\n`,
);
await mkdir(path.join(iconRoot, 'licenses'), { recursive: true });
for (const [moduleName, filename] of [
  ['lucide-react', 'LUCIDE.txt'],
  ['@heroicons/react', 'HEROICONS.txt'],
]) {
  const source = path.join(
    path.dirname(requireUI.resolve(`${moduleName}/package.json`)),
    'LICENSE',
  );
  await writeFile(path.join(iconRoot, 'licenses', filename), await readFile(source));
}
console.log(`Generated ${sources.length} UI glyphs in ${groups.size} groups.`);
